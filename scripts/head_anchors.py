#!/usr/bin/env python3
"""Find the Yeti's head in every frame of a home clip, for worn items.

Worn items (hats, headwear) are drawn on the idle Yeti's 96x96 grid.
For any other clip, this script finds how far the head moved in each
frame, relative to idle frame 0 (= the website's yeti.png pose), by
matching the idle head against the frame. The firmware shifts head items
by that offset, so they follow the head in every animation.

Reads the converted sprite headers (scripts/convert_sprite.py output), so
run it after converting a new clip, then rebuild. Stdlib only.

Usage (from the repo root):
  python scripts/head_anchors.py firmware/lib/display/ui/HeadAnchors.hpp \
      DndAnim=firmware/lib/display/ui/DndAnim.hpp@1 \
      HappyAnim=firmware/lib/display/ui/HappyAnim.hpp@1.25

  Name=header@scale: the clip's on-screen scale (96 grid clips are drawn at
  1.25 into the 120 box, native 120 clips at 1).
"""
import re
import sys
from pathlib import Path

KEY = 0xF81F                       # transparent colour key
BOX = 120                          # home Yeti box, screen px
GRID_SCALE = 1.25                  # idle grid px -> screen px
IDLE = ("YetiIdle96", "firmware/lib/display/ui/YetiIdle96.hpp", 1.25)
# Idle head (screen px inside the 120 box): face, eyes, beard top, ears.
HEAD = (22, 0, 98, 38)             # x0, y0, x1, y1
SEARCH = 20                        # +- screen px searched around idle's head


def load(path, name):
    s = Path(path).read_text()
    body = re.search(r"%s_data\[\] = \{(.*?)\};" % name, s, re.S).group(1)
    px = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", body)]
    w, h, n = map(int, re.search(
        r"SpriteAnim %s = \{\s*%s_data, (\d+), (\d+), (\d+)" % (name, name), s).groups())
    return [px[i * w * h:(i + 1) * w * h] for i in range(n)], w, h


def to_box(frame, w, h, scale):
    """Frame drawn into the 120x120 box at `scale` (nearest), as RGB tuples / None."""
    out = [[None] * BOX for _ in range(BOX)]
    for y in range(BOX):
        sy = int(y / scale)
        if sy >= h:
            continue
        for x in range(BOX):
            sx = int(x / scale)
            if sx >= w:
                continue
            p = frame[sy * w + sx]
            if p != KEY:
                out[y][x] = ((p >> 11) & 31, (p >> 5) & 63, p & 31)
    return out


def match(template, img):
    """(dx, dy) in screen px where the template fits best."""
    best = None
    for dy in range(-SEARCH, SEARCH + 1):
        for dx in range(-SEARCH, SEARCH + 1):
            cost = 0
            for (x, y, c) in template:
                tx, ty = x + dx, y + dy
                q = img[ty][tx] if 0 <= tx < BOX and 0 <= ty < BOX else None
                if q is None:
                    cost += 96
                else:
                    cost += abs(c[0] - q[0]) * 2 + abs(c[1] - q[1]) + abs(c[2] - q[2]) * 2
                if best is not None and cost >= best[0]:
                    break
            if best is None or cost < best[0]:
                best = (cost, dx, dy)
    return best[1], best[2]


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out_path = Path(sys.argv[1])
    frames, w, h = load(IDLE[1], IDLE[0])
    idle0 = to_box(frames[0], w, h, IDLE[2])
    x0, y0, x1, y1 = HEAD
    template = [(x, y, idle0[y][x]) for y in range(y0, y1, 2) for x in range(x0, x1, 2)
                if idle0[y][x] is not None]

    lines = [
        "#pragma once",
        "// Auto-generated by scripts/head_anchors.py. Do not hand-edit.",
        "// Head offset of each frame vs idle frame 0 (yeti.png), in idle grid px:",
        "// worn head items (hat, headwear) shift by this to follow the head.",
        "#include <cstdint>",
        "",
        "namespace Fuchey {",
        "",
        "struct HeadAnchors {",
        "    const int8_t* dx;",
        "    const int8_t* dy;",
        "    uint8_t frames;",
        "};",
    ]
    for arg in sys.argv[2:]:
        name, rest = arg.split("=", 1)
        path, scale = rest.rsplit("@", 1)
        clip, cw, ch = load(path, name)
        dxs, dys = [], []
        for f in clip:
            dx, dy = match(template, to_box(f, cw, ch, float(scale)))
            dxs.append(round(dx / GRID_SCALE))
            dys.append(round(dy / GRID_SCALE))
        print(f"{name}: dx={dxs} dy={dys}", file=sys.stderr)
        lines += [
            "",
            f"static constexpr int8_t {name}HeadDx[{len(clip)}] = {{{', '.join(map(str, dxs))}}};",
            f"static constexpr int8_t {name}HeadDy[{len(clip)}] = {{{', '.join(map(str, dys))}}};",
            f"static constexpr HeadAnchors {name}Head = {{{name}HeadDx, {name}HeadDy, {len(clip)}}};",
        ]
    lines += ["", "} // namespace Fuchey", ""]
    out_path.write_text("\n".join(lines))
    print(f"wrote {out_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
